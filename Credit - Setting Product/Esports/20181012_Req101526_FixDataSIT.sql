ALTER PROCEDURE [dbo].[Acc_DynamicCustSetting3rd_09]
	@srecommend INT	
	,@maxcustid INT
	,@target VARCHAR(20)
AS
BEGIN
	SET NOCOUNT ON
	
	IF (@target = 'REPLICATED' AND @@SERVERNAME = 'DBCUST') RETURN	-- run at all replicated servers
	IF (@target = 'DBCUST' AND @@SERVERNAME <> 'DBCUST') RETURN -- run at dbtrans only
	
	IF dbo.f_CheckRepTable('CustInfo') = 0 RETURN
	IF dbo.f_CheckRepTable('CustSetting') = 0 RETURN
	IF dbo.f_CheckRepTable('custOverride') = 0 RETURN	

	INSERT INTO CustOverride (custid,sporttype,bettype,minpositiontaking,maxpositiontaking,minlivepositiontaking,maxlivepositiontaking)
	SELECT 
		cs.custid,cs.sporttype, cs.bettype,0,
		(SELECT spositiontaking
		FROM custSetting cc WITH(NOLOCK)
		WHERE cc.custid=@srecommend AND cc.sporttype=cs.sporttype AND cc.bettype=cs.bettype )
		,0
		,(SELECT slivepositiontaking
		FROM custSetting cc WITH(NOLOCK)
		WHERE cc.custid=@srecommend AND cc.sporttype=cs.sporttype AND cc.bettype=cs.bettype)
	FROM custInfo ci WITH(NOLOCK)
		INNER JOIN dbo.custSetting cs WITH(NOLOCK) ON ci.custid=cs.custid
		LEFT JOIN dbo.CustOverride co WITH(NOLOCK) ON cs.custid = co.custid and cs.sporttype = co.sporttype and cs.bettype = co.bettype	
	WHERE ci.srecommend = @srecommend AND ci.custid<=@maxcustid AND ci.Enabled=1 
		AND ci.roleid IN(2,3,4) AND cs.sporttype=99 AND co.custid IS NULL

END
GO
