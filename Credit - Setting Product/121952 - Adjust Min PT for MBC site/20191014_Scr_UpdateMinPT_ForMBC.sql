ALTER PROCEDURE [dbo].[Acc_CustSetting3rd_19]
    @custid int,
    @Target VARCHAR(20) = ''
AS
BEGIN
	SET NOCOUNT ON
	
	IF (@target = 'REPLICATED' AND @@SERVERNAME = 'DBCUST') RETURN	-- run at all replicated servers
	IF (@target = 'DBCUST' AND @@SERVERNAME <> 'DBCUST') RETURN -- run at dbtrans only
	
	IF dbo.f_CheckRepTable('CustOverride') = 0 RETURN	
		
	DECLARE @roleid int, @srecommend int, @mrecommend int, @recommend int
	SELECT @roleid = roleid, @srecommend=srecommend, @mrecommend=mrecommend, @recommend=recommend FROM customer WITH (NOLOCK) WHERE custid = @custid

	UPDATE custoverride WITH(ROWLOCK, UPDLOCK)
	SET minpositiontaking = maxpositiontaking, 
		minlivepositiontaking = maxlivepositiontaking
	WHERE custoverride.custid = @custid
	
	IF @roleid = 2
	BEGIN
		EXEC dbo.Acc_CustSetting_04 @recommend = @recommend, @mrecommend = @mrecommend, @srecommend = @srecommend, @roleid = @roleid					
	END
	ELSE IF @roleid = 3
	BEGIN
		EXEC dbo.Acc_CustSetting_04 @mrecommend = @mrecommend, @srecommend = @srecommend, @roleid = @roleid				
	END
	ELSE IF @roleid= 4 
	BEGIN
		EXEC dbo.Acc_CustSetting_04 @srecommend = @srecommend, @roleid = @roleid					
	END		
	              
END    
GO
