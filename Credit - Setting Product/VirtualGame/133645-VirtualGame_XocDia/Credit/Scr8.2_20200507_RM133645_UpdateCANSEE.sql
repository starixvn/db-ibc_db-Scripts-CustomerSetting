INSERT INTO ProductLaunchedSiteCurrency (SportType, BetType, Currency, SiteID, IsLaunched, IsTest, LaunchedLevel)
SELECT @Sporttype AS SportType, @Bettype AS BetType, e.exchangeid AS Currency, s.siteid AS SiteID, 1 AS IsLaunched, 0 AS IsTest, 1 AS LaunchedLevel
FROM #OfferedSitesCurrencies tmp 
	INNER JOIN Site s WITH(NOLOCK) ON tmp.Site = s.site
	INNER JOIN exchange e WITH(NOLOCK) ON e.currency = tmp.Currency

