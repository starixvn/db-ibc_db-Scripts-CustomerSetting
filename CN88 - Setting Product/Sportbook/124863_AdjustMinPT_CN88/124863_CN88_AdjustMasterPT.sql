UPDATE al 
SET al.MasterPT_XML = (
						SELECT (
								SELECT	bs.ByteOrder	AS '@pos',
										al.M2_New		AS '@val'
								FROM dbo.CS_ByteSeq bs WITH (NOLOCK)
								WHERE bs.Type = 'PTSetting' 
									AND bs.SportType = al.sporttype AND bs.BetType = al.BetType AND bs.IsLive = al.IsLive
								FOR XML PATH('r')
									, TYPE
								)
						FOR XML PATH('root')
							, TYPE
						)
FROM #AgentList al

