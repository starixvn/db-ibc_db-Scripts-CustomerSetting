CREATE PROC DBA_InsertMissingSettingLicensee
	@custid INT
AS
BEGIN
	SET NOCOUNT ON 
	
	INSERT INTO tmpDep_CustSettingMode
			   ([CustID]
			   ,[IsGroupedPT]
			   ,[IsGroupedComm]
			   ,[IsGroupedBetLimit]
			   ,[IsGroupedStakeLevel])
    SELECT [CustID]
	   ,[IsGroupedPT]
	   ,[IsGroupedComm]
	   ,[IsGroupedBetLimit]
	   ,[IsGroupedStakeLevel]
	FROM DBACC.bodb02.dbo.Dep_CustSettingMode WITH(NOLOCK)
	WHERE custid = @custid
	
	INSERT INTO tmpDep_CustPTSetting_Member
           ([CustID]
           ,[SportType]
           ,[BetType]
           ,[IsLive]
           ,[SuperPT]
           ,[MasterPT]
           ,[AgentPT])
    SELECT [CustID]
           ,[SportType]
           ,[BetType]
           ,[IsLive]
           ,[SuperPT]
           ,[MasterPT]
           ,[AgentPT]
	FROM DBACC.bodb02.dbo.Dep_CustPTSetting_Member WITH(NOLOCK)
	WHERE custid = @custid
	
	INSERT INTO tmpDep_CustBetSetting_Member
           ([CustID]
           ,[SportType]
           ,[BetType]
           ,[MinBet]
           ,[MaxBet]
           ,[MaxPerMatch])
    SELECT [CustID]
           ,[SportType]
           ,[BetType]
           ,[MinBet]
           ,[MaxBet]
           ,[MaxPerMatch]
	FROM DBACC.bodb02.dbo.Dep_CustBetSetting_Member WITH(NOLOCK)
	WHERE custid = @custid
	
	INSERT INTO tmpDep_CustStakeLevel_Member
           ([CustID]
           ,[SportType]
           ,[BetType]
           ,[StakeLevelList]
           ,[LastUpdated])
    SELECT [CustID]
           ,[SportType]
           ,[BetType]
           ,[StakeLevelList]
           ,[LastUpdated]
	FROM DBACC.bodb02.dbo.Dep_CustStakeLevel_Member WITH(NOLOCK)
	WHERE custid = @custid
		
	INSERT INTO tmpDep_CustProductStatus
           ([CustID]
           ,[bitmapIsHidden]
           ,[bitmapIsDisabled])
	SELECT [CustID]
           ,[bitmapIsHidden]
           ,[bitmapIsDisabled]
	FROM DBACC.bodb02.dbo.Dep_CustProductStatus WITH(NOLOCK)
	WHERE custid = @custid
   
	INSERT INTO tmpDep_CustBetSettingGame_Member
           ([CustID]
           ,[SportType]
           ,[BetType]
           ,[MinBet]
           ,[MaxBet]
           ,[MaxPerMatch]
           ,[MaxPerNumber]
           ,[MaxPayoutPerMatch])
    SELECT [CustID]
           ,[SportType]
           ,[BetType]
           ,[MinBet]
           ,[MaxBet]
           ,[MaxPerMatch]
           ,[MaxPerNumber]
           ,[MaxPayoutPerMatch]	
	FROM DBACC.bodb02.dbo.Dep_CustBetSettingGame_Member WITH(NOLOCK)
	WHERE custid = @custid	   	
	
	EXEC Acc_DynamicCustSetting3rd_19 @custid = @custid
		
END
GO

