	WHILE (1=1)
	BEGIN
		UPDATE TOP (1) t
		SET isDeleted = 1,
			@Doing = Doing
		FROM @Log t
		WHERE isDeleted = 0 
		
		IF @@ROWCOUNT = 0 
			BREAK;
			
		INSERT INTO #tblLog(LogID,CustID)
		SELECT LogID, CustID
		FROM UserLog_UserControl WITH(NOLOCK)
		where ActionID = 5566
