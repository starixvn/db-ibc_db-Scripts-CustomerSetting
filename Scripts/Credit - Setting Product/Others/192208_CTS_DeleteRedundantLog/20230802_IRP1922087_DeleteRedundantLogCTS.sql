			DELETE u
			FROM UserLog_UserControl u WITH(ROWLOCK)
				INNER JOIN @tmpLog t ON u.LogID = t.LogID AND u.CustID = t.CustID
			WHERE ActionID = 5566
				AND Doing = @Doing				
				AND logdate BETWEEN @fromdate AND @todate
				
