ALTER PROCEDURE [dbo].[Acc_DynamicCustomerInfo_09]
	@srecommend INT		
	,@maxcustid INT
	,@max_SubAccid INT
	,@target VARCHAR(20)
AS
BEGIN
	SET NOCOUNT ON
	
	IF (@target = 'REPLICATED' AND @@SERVERNAME IN ('DBCUST','SITDBCUST','DB233','DB230\SQLSERVER2008R2')) RETURN	-- run at all replicated servers
	IF (@target = 'DBCUST' AND @@SERVERNAME NOT IN ('DBCUST','SITDBCUST','DB233','DB230\SQLSERVER2008R2')) RETURN -- run at dbcust only
		
	IF dbo.f_CheckRepTable('Customer') = 0 RETURN
	IF dbo.f_CheckRepTable('Custinfo') = 0 RETURN	
	
	CREATE TABLE #MemberTemp
	(
		CustID INT PRIMARY KEY CLUSTERED		
	)

	CREATE TABLE #SMATemp
	(
		CustID INT PRIMARY KEY CLUSTERED
	)

	CREATE TABLE #MemberTempBatch
	(
		CustID	INT PRIMARY KEY CLUSTERED	
	)	
	
	INSERT INTO #MemberTemp (CustID)
	SELECT custid
	FROM Custinfo WITH (NOLOCK)
	WHERE srecommend = @srecommend AND roleid = 1 AND custid <= @maxcustid	
		
	INSERT INTO #SMATemp (CustID)
	SELECT custid
	FROM Custinfo WITH (NOLOCK)
	WHERE srecommend = @srecommend AND roleid IN (2,3,4) AND custid <= @maxcustid 
	
	IF dbo.f_CheckRepTable('CustSuperProfile') = 1
	BEGIN
		--Super Level
		UPDATE c 
		SET c.lastname = '',
			c.firstname = '',
			c.phone = '',
			c.mobilephone = '',
			c.email = '',
			c.fax = '',
			c.remark = ''		
		FROM dbo.CustSuperProfile c WITH (ROWLOCK)
		WHERE c.custid = @srecommend
	END

	--Master, Agent Level
	UPDATE c 
	SET c.lastname = '',
		c.firstname = '',
		c.phone = '',
		c.mobilephone = '',
		c.email = '',
		c.fax = '',
		c.remark = ''		
	FROM Customer c WITH (ROWLOCK)
		INNER JOIN #SMATemp a ON a.CustID = c.custid
	WHERE c.custid <> @srecommend

	IF dbo.f_CheckRepTable('custSub') = 1
	BEGIN
		--Sub account
		UPDATE c 
		SET c.lastname = '',
			c.firstname = '',
			c.closed = 1		
		FROM dbo.custSub c WITH (ROWLOCK)
			INNER JOIN #SMATemp a ON a.CustID = c.custid
		WHERE c.subaccid <= @max_SubAccid
	END

	--Member Level
	WHILE EXISTS(SELECT 1 FROM #MemberTemp)
	BEGIN
		DELETE TOP (4000) #MemberTemp OUTPUT DELETED.* INTO #MemberTempBatch

		IF @@ROWCOUNT=0
			BREAK		

		UPDATE c 
		SET c.lastname = '',
			c.firstname = '',
			c.phone = '',
			c.mobilephone = '',
			c.email = '',
			c.fax = '',
			c.remark = ''		
		FROM Customer c WITH (ROWLOCK)
			INNER JOIN #MemberTempBatch m ON m.CustID = c.custid

		TRUNCATE TABLE #MemberTempBatch
	END
	
	DROP TABLE #SMATemp
	DROP TABLE #MemberTemp
END
GO

