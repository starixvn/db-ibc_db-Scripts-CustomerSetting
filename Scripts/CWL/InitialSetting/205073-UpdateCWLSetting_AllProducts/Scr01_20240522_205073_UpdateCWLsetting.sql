--Update new setting
DECLARE @ProductId INT, 
		@GroupId   INT, 
		@Level1    MONEY, 
		@Level2    MONEY, 
		@Level3    MONEY, 
		@Level101  MONEY, 
		@Level102  MONEY, 
		@Currency  VARCHAR(MAX),
		@IsDeposit BIT = 0

WHILE EXISTS (SELECT 1 FROM #tmpProductSetting WHERE IsFinished=0)
BEGIN
	UPDATE TOP (1) t
	SET t.IsFinished = 1
		,@ProductId	= t.ProductID
		,@GroupId	= t.GroupID
		,@Level1    = t.Level1
		,@Level2    = t.Level2
		,@Level3    = t.Level3
		,@Level101  = t.Level101
		,@Level102  = t.Level102
		,@Currency  = ISNULL(t.Currency,'')
		,@IsDeposit = t.IsDeposit
	FROM #tmpProductSetting t
	WHERE IsFinished=0

	--Update
	EXEC dbo.NAP_CWL_Update_Settings 
		@ProductId    = @ProductID
	  , @GroupId      = @GroupID
	  , @Level1       = @Level1
	  , @Level2       = @Level2
	  , @Level3       = @Level3
	  , @Level101     = @Level101
	  , @Level102     = @Level102
	  , @Currency	   = @Currency
	  , @IsDeposit	   = @IsDeposit

	WAITFOR DELAY '00:00:0.200'
END
