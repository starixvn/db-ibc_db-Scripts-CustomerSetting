INSERT INTO [dbo].[crmDefaultCommTool]
           ([DefaultCommID]
           ,[CustID]
           ,[SettingID]
           ,[SettingType])

SELECT @maxID+t.ID,c.CustID,s.SettingID,3
FROM bodb02.dbo.Customer  c WITH(NOLOCK)
	INNER JOIN #tmp t ON c.UserName=t.Headline
	INNER JOIN crmSetting s WITH(NOLOCK) ON RTRIM(t.Tool)=s.SettingValue AND s.SettingName='Communication' AND s.SiteOffer=2
WHERE NOT EXISTS(SELECT TOP 1 1 FROM [crmDefaultCommTool] aa WITH(NOLOCK) WHERE aa.DefaultCommID=@maxID+t.ID AND aa.CustID=c.CustID AND aa.SettingID=s.SettingID AND aa.SettingType=3)


