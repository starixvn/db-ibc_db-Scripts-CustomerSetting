INSERT INTO #supers(custid, PT)
SELECT ci.custid, t.PT 	
FROM Dep_custsuper cs WITH (NOLOCK) 	
	INNER JOIN custinfo ci WITH(NOLOCK) ON cs.custid = ci.custid
	INNER JOIN @tmpSite t ON cs.site = t.site
WHERE ci.Enabled=1

CREATE TABLE #tblCust (custid INT PRIMARY KEY, srecommend INT)	
CREATE TABLE #tblCustNoGrouped (custid INT PRIMARY KEY, srecommend INT)
CREATE TABLE #tmpCust (custid INT PRIMARY KEY, srecommend INT)	
CREATE TABLE #tblSMA (custid INT PRIMARY KEY, srecommend INT, roleid TINYINT)	
CREATE TABLE #DummyMaster (CustID INT PRIMARY KEY)

INSERT INTO #DummyMaster(CustID)
SELECT CustID 
FROM Custinfo WITH(NOLOCK) 
WHERE srecommend IN (SELECT custid FROM #Supers)
	AND roleid=3 
	AND (username LIKE '%Acc%' OR username LIKE '%LocalBank%' OR username LIKE '%ClearBal%')

INSERT INTO #tblSMA(CustID,srecommend,roleid)
SELECT CustID, srecommend, roleid 
FROM Custinfo WITH(NOLOCK) 
WHERE srecommend IN (SELECT custid FROM #Supers)
	AND roleid IN (2,3,4) 
	AND mrecommend NOT IN (SELECT custid FROM #DummyMaster)
	AND custid > @max_custid
	
INSERT INTO #tblCust (custid,srecommend)
SELECT custid,srecommend
FROM custinfo WITH(NOLOCK)
WHERE srecommend IN (SELECT custid FROM #Supers)
	AND roleid = 1
	AND mrecommend NOT IN (SELECT custid FROM #DummyMaster)
	AND custid > @max_custid
	AND custid NOT IN (SELECT custid FROM Dep_CustBAActive WITH(NOLOCK))

INSERT INTO #tblCustNoGrouped(custid,srecommend)
SELECT cs.custid,t.srecommend
FROM Dep_CustSettingMode cs WITH(NOLOCK)
	INNER JOIN #tblCust t ON cs.custid = t.custid
WHERE IsGroupedPT = 0

UPDATE cs
SET cs.spositiontaking= CASE WHEN roleid = 4 THEN s.PT ELSE cs.spositiontaking END,
	cs.mpositiontaking= CASE WHEN roleid IN(4,3) THEN s.PT ELSE cs.mpositiontaking END,
	cs.apositiontaking= CASE WHEN roleid IN(4,2) THEN s.PT ELSE cs.apositiontaking END
FROM Dep_CustSetting cs WITH(ROWLOCK)
	INNER JOIN #tblSMA t ON cs.CustID=t.CustID	
	INNER JOIN #Supers s ON t.srecommend = s.custid

UPDATE cs
SET cs.SuperPT = CASE WHEN roleid = 4 THEN s.PT*100 ELSE cs.SuperPT END,
	cs.MasterPT = CASE WHEN roleid IN(4,3) THEN s.PT*100 ELSE cs.MasterPT END,
	cs.AgentPT = CASE WHEN roleid IN(4,2) THEN s.PT*100 ELSE cs.AgentPT END
FROM Dep_CustPTSetting_Agent cs WITH(ROWLOCK)
	INNER JOIN #tblSMA t ON cs.CustID=t.CustID	
	INNER JOIN #Supers s ON t.srecommend = s.custid

UPDATE cs
SET SuperPT  = 0
	,MasterPT = 0
	,AgentPT  = s.PT*100
FROM dbo.Dep_CustPTGroupSetting_Member cs WITH(UPDLOCK,ROWLOCK)
	INNER JOIN #tblSMA t ON cs.CustID=t.CustID
	INNER JOIN #Supers s ON t.srecommend = s.custid
WHERE roleid = 2
	AND sporttype = 43

WHILE(1=1)
BEGIN
	DELETE TOP (1000) #tblCustNoGrouped OUTPUT DELETED.* INTO #tmpCust
	
	IF @@ROWCOUNT = 0
		BREAK;
		
	UPDATE cs
	SET cs.AgentPT=s.PT*100
	FROM Dep_CustPTSetting_Member cs WITH(ROWLOCK,UPDLOCK)
		INNER JOIN #tmpCust t ON cs.CustID=t.CustID
		INNER JOIN #Supers s ON t.srecommend = s.custid
	WHERE sporttype = 43
		
	TRUNCATE TABLE #tmpCust
END	

WHILE(1=1)
BEGIN
	DELETE TOP (500) #tblCust OUTPUT DELETED.* INTO #tmpCust
	
	IF @@ROWCOUNT = 0
		BREAK;
		
	UPDATE cs
	SET cs.apositiontaking=s.PT
	FROM Dep_CustSetting cs WITH(ROWLOCK,UPDLOCK)
		INNER JOIN #tmpCust t ON cs.CustID=t.CustID
		INNER JOIN #Supers s ON t.srecommend = s.custid
		
	TRUNCATE TABLE #tmpCust
END	

