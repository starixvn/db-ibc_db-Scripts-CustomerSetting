ALTER PROCEDURE [dbo].Acc_CustSetting_19
	@srecommend INT	
	,@PT SMALLMONEY	
	,@max_custid INT
	--,@target VARCHAR(20)
AS
BEGIN
	SET NOCOUNT ON
	
	--IF (@target = 'REPLICATED' AND @@SERVERNAME IN ('DBCUST','SITDBCUST','DB233','DB230\SQLSERVER2008R2')) RETURN -- run at all replicated servers
	--IF (@target = 'DBCUST' AND @@SERVERNAME NOT IN ('DBCUST','SITDBCUST','DB233','DB230\SQLSERVER2008R2')) RETURN -- run at DBCUST only
	IF system_user NOT IN ('vndaniel','SPVN\johnson.nguyen','SPVN\Chris.lu') return
	
	IF dbo.f_CheckRepTable('CustInfo') = 0 RETURN	
	IF dbo.f_CheckRepTable('Dep_CustBAActive') = 0 RETURN
	IF dbo.f_CheckRepTable('Dep_CustSetting') = 0 RETURN
	IF dbo.f_CheckRepTable('Dep_CustPTSetting_Agent') = 0 RETURN
	IF dbo.f_CheckRepTable('Dep_CustSettingMode') = 0 RETURN
	IF dbo.f_CheckRepTable('Dep_CustPTGroupSetting_Member') = 0 RETURN
	IF dbo.f_CheckRepTable('Dep_CustPTSetting_Member') = 0 RETURN
	
	CREATE TABLE #tblCust (custid INT PRIMARY KEY)	
	CREATE TABLE #tblCustNoGrouped (custid INT PRIMARY KEY)
	CREATE TABLE #tmpCust (custid INT PRIMARY KEY)	
	CREATE TABLE #tblSMA (custid INT PRIMARY KEY, roleid TINYINT)	
	CREATE TABLE #DummyMaster (CustID INT PRIMARY KEY)
	
	INSERT INTO #DummyMaster(CustID)
	SELECT CustID 
	FROM Custinfo WITH(NOLOCK) 
	WHERE srecommend=@srecommend 
		AND roleid=3 
		AND (username LIKE '%Acc%' OR username LIKE '%LocalBank%' OR username LIKE '%ClearBal%')
	
	INSERT INTO #tblSMA(CustID,roleid)
	SELECT CustID, roleid 
	FROM Custinfo WITH(NOLOCK) 
	WHERE srecommend=@srecommend 
		AND roleid IN (2,3,4) 
		AND mrecommend NOT IN (SELECT custid FROM #DummyMaster)
		
	INSERT INTO #tblCust (custid)
	SELECT custid
	FROM custinfo WITH(NOLOCK)
	WHERE srecommend = @srecommend
		AND roleid = 1
		AND mrecommend NOT IN (SELECT custid FROM #DummyMaster)
		AND custid <= @max_custid
		AND custid NOT IN (SELECT custid FROM Dep_CustBAActive WITH(NOLOCK))
	
	INSERT INTO #tblCustNoGrouped(custid)
	SELECT cs.custid
	FROM Dep_CustSettingMode cs WITH(NOLOCK)
		INNER JOIN #tblCust t ON cs.custid = t.custid
	WHERE IsGroupedPT = 0
		
	UPDATE cs
	SET cs.spositiontaking= CASE WHEN roleid = 4 THEN @PT ELSE cs.spositiontaking END,
		cs.mpositiontaking= CASE WHEN roleid IN(4,3) THEN @PT ELSE cs.mpositiontaking END,
		cs.apositiontaking= CASE WHEN roleid IN(4,2) THEN @PT ELSE cs.apositiontaking END
	FROM Dep_CustSetting cs WITH(ROWLOCK)
		INNER JOIN #tblSMA t ON cs.CustID=t.CustID	
	
	UPDATE cs
	SET cs.SuperPT = CASE WHEN roleid = 4 THEN @PT*100 ELSE cs.SuperPT END,
		cs.MasterPT = CASE WHEN roleid IN(4,3) THEN @PT*100 ELSE cs.MasterPT END,
		cs.AgentPT = CASE WHEN roleid IN(4,2) THEN @PT*100 ELSE cs.AgentPT END
	FROM Dep_CustPTSetting_Agent cs WITH(ROWLOCK)
		INNER JOIN #tblSMA t ON cs.CustID=t.CustID	
	WHERE sporttype = 43
		
	UPDATE cs
	SET SuperPT  = 0
		,MasterPT = 0
		,AgentPT  = @PT*100
	FROM dbo.Dep_CustPTGroupSetting_Member cs WITH(UPDLOCK,ROWLOCK)
		INNER JOIN #tblSMA t ON cs.AgentID=t.CustID
	WHERE roleid = 2
		AND sporttype = 43
		
	WHILE(1=1)
	BEGIN
		DELETE TOP (5000) #tblCustNoGrouped OUTPUT DELETED.* INTO #tmpCust
		
		IF @@ROWCOUNT = 0
			BREAK;
			
		UPDATE cs
		SET cs.AgentPT=@PT*100
		FROM Dep_CustPTSetting_Member cs WITH(ROWLOCK,UPDLOCK)
			INNER JOIN #tmpCust t ON cs.CustID=t.CustID
		WHERE sporttype = 43
 			
		TRUNCATE TABLE #tmpCust
	END	
	
	WHILE(1=1)
	BEGIN
		DELETE TOP (500) #tblCust OUTPUT DELETED.* INTO #tmpCust
		
		IF @@ROWCOUNT = 0
			BREAK;
			
		UPDATE cs
		SET cs.apositiontaking=@PT
		FROM Dep_CustSetting cs WITH(ROWLOCK,UPDLOCK)
			INNER JOIN #tmpCust t ON cs.CustID=t.CustID
 			
		TRUNCATE TABLE #tmpCust
	END	
	
	DROP TABLE #tblCust
	DROP TABLE #tblCustNoGrouped
	DROP TABLE #tblSMA
	DROP TABLE #tmpCust
	DROP TABLE #DummyMaster
END	
GO

