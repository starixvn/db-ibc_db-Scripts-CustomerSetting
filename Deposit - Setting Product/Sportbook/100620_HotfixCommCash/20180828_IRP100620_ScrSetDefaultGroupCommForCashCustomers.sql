CREATE TABLE #Result(custid INT, site VARCHAR(100),ErrCode INT, ErrMsg NVARCHAR(2000))

DECLARE @custid INT, 
	@site VARCHAR(100),	
	@Langkey VARCHAR(10) = 'en-US',
	@ErrCode INT = 0,
	@ErrMsg nvarchar(2000) = '' 
	
-- For deployer info
DECLARE @cust_cnt INT, @index INT = 0

SET @cust_cnt = (SELECT COUNT(*) FROM #tmpCust)

DECLARE @msg NVARCHAR(200) = 'Currently at order %d, custID: %d.'

DECLARE @msg_total NVARCHAR(200) = 'Total of customers: %d.'

RAISERROR (@msg_total, 0, 1, @cust_cnt) WITH NOWAIT

WHILE(1=1)
BEGIN
	SELECT @ErrCode = 0, @ErrMsg = ''
	
	UPDATE TOP (1) c
	SET @custID = custID,
		@site = site,
		isFinished = 1
	FROM #tmpCust c
	WHERE isFinished = 0
	
	IF (@@ROWCOUNT =0)
		BREAK;
	
	SET @index = @index + 1
	
	RAISERROR (@msg, 0, 1,@index, @custID) WITH NOWAIT
	
	EXEC dbo.Lrf_CustomerSetDefaultComm
		@CustID = @custID,
		@LicenseeName = @site,
		@Langkey = @Langkey,
		@ErrCode = @ErrCode OUT,
		@ErrMsg = @ErrMsg OUT
	
	IF @ErrCode > 0 
	BEGIN
		INSERT INTO #Result(custID,site,ErrCode,ErrMsg)
		SELECT @custID,@site,@ErrCode,@ErrMsg
	END
	
	WAITFOR DELAY '0:0:0.2'
END

