CREATE TABLE #TmpList (CustID INT, recommend INT)

INSERT INTO #TmpList (CustID, recommend)
SELECT CustID, recommend
FROM CustInfo WITH (NOLOCK)
WHERE custid IN (28127703,28128447,28128518,28128779,28129153,28129176,28129632,28129915,28130136,28130253,28130347,28130622,28130695,28130724,28130731,28130737,
