				28135286,28136475,28136531)

UPDATE c
SET c.danger = a.Danger,
	c.danger2 = a.Danger2,
	c.danger3 = a.Danger3
FROM dbo.custInfo c WITH (ROWLOCK, UPDLOCK)
	INNER JOIN #TmpList tmp ON c.custid = tmp.CustID
	INNER JOIN custInfo a ON a.custid = tmp.recommend
